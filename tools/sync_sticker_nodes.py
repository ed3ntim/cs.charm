"""Copy the sticker finish node groups from cs.sticker into cs.charm.

The Sticker Slab shades its sticker with the same finish groups as
cs.sticker (Paper, Glitter, Holo, Foil, Gold, Lenticular, Embroidered).
Extensions cannot depend on each other, so instead of importing cs_sticker
at runtime the group builders are copied into
``cs_charm/nodes/sticker_groups.py`` with their own group name prefix and
version key (both add-ons can be installed side by side).

    python tools/sync_sticker_nodes.py [--source ../cs.sticker] [--check]

``--check`` only reports whether the copy is up to date (exit code 1 if
not). Never edit sticker_groups.py by hand: change cs.sticker, then sync.
"""

import argparse
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TARGET = os.path.join(ROOT, "cs_charm", "nodes", "sticker_groups.py")
DEFAULT_SOURCE = os.path.join(os.path.dirname(ROOT), "cs.sticker")
SOURCE_FILE = os.path.join("cs_sticker", "nodes", "groups.py")

PREFIX = "CS2 Slab "
VERSION_KEY = "cs_charm_sticker_version"

NOTE = (
    "Generated by tools/sync_sticker_nodes.py from cs.sticker\n"
    "(cs_sticker/nodes/groups.py). Do not edit: change cs.sticker and sync.\n"
    "Group names use the prefix \"{prefix}\" and the version key \"{key}\",\n"
    "so the groups never clash with an installed cs.sticker.\n\n"
)

_RULES = (
    (re.compile(r'^PREFIX = "CS2 "$', re.M), f'PREFIX = "{PREFIX}"'),
    (re.compile(r'^VERSION_KEY = "cs_sticker_version"$', re.M), f'VERSION_KEY = "{VERSION_KEY}"'),
)


def transform(source_text):
    """cs.sticker groups.py -> cs.charm sticker_groups.py text."""
    text = source_text.replace("\r\n", "\n")
    for pattern, repl in _RULES:
        text, count = pattern.subn(repl, text)
        if count != 1:
            raise ValueError(f"cs.sticker groups.py changed: expected one match for {pattern.pattern}")
    # The note goes at the start of the module docstring.
    head, sep, rest = text.partition('"""')
    if not sep:
        raise ValueError("cs.sticker groups.py has no module docstring")
    note = NOTE.format(prefix=PREFIX, key=VERSION_KEY)
    return f'{head}"""{note}{rest}'


def source_version(text):
    m = re.search(r"^GROUP_VERSION = (\d+)", text, re.M)
    return int(m.group(1)) if m else None


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--source", default=DEFAULT_SOURCE, help="cs.sticker repository (default: sibling folder)")
    ap.add_argument("--check", action="store_true", help="only check, do not write")
    args = ap.parse_args(argv)

    src = os.path.join(args.source, SOURCE_FILE)
    with open(src, encoding="utf-8") as fh:
        wanted = transform(fh.read())
    current = ""
    if os.path.isfile(TARGET):
        with open(TARGET, encoding="utf-8") as fh:
            current = fh.read()
    if current == wanted:
        print(f"sticker_groups.py is up to date (cs.sticker GROUP_VERSION {source_version(wanted)})")
        return 0
    if args.check:
        print("sticker_groups.py is out of date: run tools/sync_sticker_nodes.py")
        return 1
    with open(TARGET, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(wanted)
    print(f"wrote {os.path.relpath(TARGET, ROOT)} (cs.sticker GROUP_VERSION {source_version(wanted)})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
